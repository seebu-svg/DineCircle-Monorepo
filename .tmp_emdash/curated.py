# Lone em dash used as an "empty value" placeholder in UI.
PLACEHOLDER_PAIRS = [("'—'", "'-'")]

ROOTS = ["website", "DineCircle-master/lib", "DineCircle-master/server/src",
         "partnerapp/lib", "partnerapp/tool", "DineCircle-master/tool"]
EXTS = {".dart", ".ts", ".js", ".html", ".py", ".sql"}

def files():
    for root in ROOTS:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in {"node_modules", "build", ".dart_tool", "dist"}]
            for fn in filenames:
                if os.path.splitext(fn)[1] in EXTS:
                    yield os.path.join(dirpath, fn)

counts = {old: 0 for old, _ in PAIRS + PLACEHOLDER_PAIRS}
for path in files():
    text = open(path, encoding="utf-8").read()
    original = text
    for old, new in PAIRS + PLACEHOLDER_PAIRS:
        if old in text:
            counts[old] += text.count(old)
            text = text.replace(old, new)
    if text != original:
        open(path, "w", encoding="utf-8").write(text)

missing = [old for old, n in counts.items() if n == 0]
print("applied distinct pairs:", sum(1 for n in counts.values() if n))
print("total replacements:", sum(counts.values()))
print("NOT FOUND:", len(missing))
for m in missing:
    print("  -", m[:110])
